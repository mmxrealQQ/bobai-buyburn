// GO-LIVE BUILD of the Brain page (2026-09-27). Assembles a deployable site in .golive-build/ from the live
// dashboard/ plus the lab's Brain page and terminal, so what goes live is exactly what was tested:
//   node temp/newpage/golive.mjs            -> build .golive-build/
//   node temp/newpage/golive.mjs --preview  -> build + deploy to the bobai-dashboard PREVIEW branch "golive"
//                                              (https://golive.bobai-dashboard.pages.dev — not brainonbnb.com)
//   node temp/newpage/golive.mjs --apply    -> THE GO-LIVE (operator's go only): the same changes written into
//                                              dashboard/ itself, so every later deploy-dashboard.mjs keeps the new page
//                                              (a build outside dashboard/ would be overwritten by the next normal
//                                              deploy). Then: node scripts/deploy-dashboard.mjs, check, commit.
// Every step is idempotent: --apply twice changes nothing the second time.
//
// What it changes against dashboard/ (and nothing else):
//   1. index.html (Classic) gets the terminal's nav button and its popup shell, taken from the lab's Classic page
//   2. brain/ (the new front page, generated by build.mjs from that Classic page) and terminal/ (scene, figures, clips)
//   3. _worker.js: / = the Brain page, /classic = Classic, ?embed=1 / frame requests get the window look (snippet file)
//   4. _headers: the CSP lets our own pages sit in our own frames, the candle ledger be read, and blob: images show
//   5. _routes.json: the worker runs for /, /classic and the pages the windows embed (it ran only for /api etc.)
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
const LAB = path.join(ROOT, 'temp', 'newpage', 'lab'); // moved out of a session scratchpad 2026-09-27
const APPLY = process.argv.includes('--apply');
// inside the repo either way: _worker.js imports ../shared
const OUT = APPLY ? path.join(ROOT, 'dashboard') : path.join(ROOT, '.golive-build');
const rd = (p) => fs.readFileSync(p, 'utf8');
const must = (ok, what) => { if (!ok) throw new Error('golive: ' + what); };

// ALL OR NOTHING (2026-10-02): a shell held dashboard/terminal, the apply copied the lab's stale brain/ in and then died
// with EPERM on terminal/ — before the noindex check below — and the next deploy shipped a noindex front page with old
// app.js/styles. Both folders must be movable before a single file is written.
if (APPLY) for (const d of ['brain', 'terminal']) {
  const p = path.join(OUT, d);
  if (fs.existsSync(p)) { try { fs.renameSync(p, p + '.locktest'); fs.renameSync(p + '.locktest', p); } catch (e) { throw new Error(`golive: dashboard/${d} is locked (${e.code}) — close what holds it, nothing was changed`); } }
}
if (!APPLY) { fs.rmSync(OUT, { recursive: true, force: true }); fs.cpSync(path.join(ROOT, 'dashboard'), OUT, { recursive: true }); }
for (const d of ['brain', 'terminal']) { fs.rmSync(path.join(OUT, d), { recursive: true, force: true }); fs.cpSync(path.join(LAB, d), path.join(OUT, d), { recursive: true }); }
// only the clips the terminal plays go live. Since 2026-09-28 (operator: "use all animations and videos") that is every
// take again, the older pose-start ones with a soft fade — except the ones withheld as cut (temp/terminal/anim/cut.txt)
{
  const anim = path.join(OUT, 'terminal', 'anim');
  const cut = new Set(rd(path.join(ROOT, 'temp/terminal/anim/cut.txt')).split(/\r?\n/).map((l) => l.trim()).filter((l) => l && !l.startsWith('#')));
  // A TAKE WRITTEN "WITHHELD" IS WITHHELD (2026-10-12: five takes noted WITHHELD on 30.9.-2.10. had lost their name line
  // and went live anyway — hub-defi-v2's blue board turned his arms blue): a note "WITHHELD: <take> (" with no name line
  // and no later release or rescue of that take stops the build
  {
    const L = rd(path.join(ROOT, 'temp/terminal/anim/cut.txt')).split(/\r?\n/), lost = [];
    L.forEach((l, i) => {
      if (!l.startsWith('#') || !l.includes('WITHHELD')) return;
      for (const n of (l.split('WITHHELD').slice(1).join(' ').split('(')[0].match(/\b(?:hub|rest|idle)-[a-z0-9-]*[a-z0-9]/g) || [])) {
        if (cut.has(n)) continue;
        const freed = L.some((m, j) => j > i && m.includes(n) && /releas|rescued/i.test(L.slice(Math.max(0, j - 2), j + 1).join(' ')));
        if (!freed) lost.push(`${n} (line ${i + 1})`);
      }
    });
    must(!lost.length, 'cut.txt: noted WITHHELD but no name line and never released: ' + lost.join(', '));
  }
  for (const f of fs.readdirSync(anim)) {
    // only what the terminal plays (hub takes + the standing ones): the older pose-start takes never play again (2026-09-28)
    // a kept clip keeps its <name>.pack.wide marker too: without it a wide take plays in the normal framing and he
    // jumps smaller and aside (2026-09-28, the first wide takes)
    // every waiting take (2026-09-30: rest-v3..v6 for the launch morning would have been dropped here)
    // idle-v3/-v4 (2026-10-02): more greeting waves
    // rest-s1..s6 (2026-10-11): the short calm moments (rest_pingpong.py)
    const m = f.match(/^(idle(?:-v\d)?|rest(?:-[vs]\d)?|hub-[a-z0-9-]+)\.pack\.(mp4|wide)$/);
    const keep = !!m && !cut.has(m[1]);
    if (!keep) fs.rmSync(path.join(anim, f), { recursive: true, force: true });
  }
  execSync(`node "${path.join(ROOT, 'temp/newpage/clips.mjs')}" "${path.join(OUT, 'terminal')}"`, { stdio: 'inherit' });
}

// 1) Classic + terminal popup
{
  const lab = rd(path.join(LAB, 'index.html')); let prod = rd(path.join(OUT, 'index.html'));
  const m = lab.match(/\n[ \t]*<button class="nb nbt" id="btOpen"[^\n]*/); must(m, 'terminal button not found in the lab page');
  const prev = lab.slice(0, m.index).split('\n').pop(); must(prod.includes(prev), 'anchor line for the terminal button missing in dashboard/index.html');
  if (!prod.includes('id="btOpen"')) { const k = prod.indexOf(prev) + prev.length; prod = prod.slice(0, k) + m[0] + prod.slice(k); }
  const i = lab.indexOf('\n<!-- BOBAI BRAIN TERMINAL.'); must(i > 0, 'terminal block not found in the lab page');
  // AFTER GO-LIVE TOO (2026-10-01): the block used to go in only when missing, so once live it was never renewed — the
  // ?v= of terminal.js stayed the go-live one and a 4-hour cache served the old terminal. The block is the lab's: it is
  // replaced as a whole every time (it ends where </body> begins, where it was put).
  const block = lab.slice(i + 1, lab.lastIndexOf('</body>')).trimEnd() + '\n'; // trimmed: every apply used to add a blank line
  if (!prod.includes('<!-- BOBAI BRAIN TERMINAL.')) { const j = prod.lastIndexOf('</body>'); prod = prod.slice(0, j) + block + '\n' + prod.slice(j); }
  else { const pi = prod.indexOf('<!-- BOBAI BRAIN TERMINAL.'), pj = prod.lastIndexOf('</body>'); must(pj > pi, 'terminal block not before </body> in dashboard/index.html'); prod = prod.slice(0, pi) + block + '\n' + prod.slice(pj); }
  must(prod.includes(lab.match(/terminal\/terminal\.js\?v=\d+/)[0]), 'terminal.js ?v= of the lab not in the page');
  must(!/name="robots" content="noindex/.test(prod), 'Classic page carries noindex');
  // THE ROADMAP AT GO-LIVE (operator, 2026-09-27): the terminal itself is shipped the moment this goes out, and the
  // Giggle Academy donation is the next dated step. Both pages read this one list (the Brain page is built from it).
  // THE BRAINMAP (2026-10-09) replaced that list and already names the terminal and the Giggle donation: the anchors
  // below belong to the old list and are only looked for while it is there
  if (!prod.includes('The <em>Brain</em>map')) {
  const agents = '<li><span class="ck">&#x2713;</span><span>Four agent pieces live — Pool Scanner, Brain Plaza, Agent Services, DeFi Agent</span></li>';
  must(prod.includes(agents), 'roadmap anchor (agent pieces) not found');
  if (!prod.includes('Brain Terminal — ')) prod = prod.replace(agents, agents + '\n        <li><span class="ck">&#x2713;</span><span>Brain Terminal — BOBAI’s work on BNB Chain as a live film</span></li>');
  const keep = '<li><span class="ck">&#x2713;</span><span>Keep burning. Bot runs every 10 minutes.</span></li>';
  must(prod.includes(keep), 'roadmap anchor (keep burning) not found');
  if (!prod.includes('Giggle Academy donation on Nov 20')) prod = prod.replace(keep, '<li><span style="color:var(--muted)">&#x25cb;</span><span>Giggle Academy donation on Nov 20 (UN World Children’s Day)</span></li>\n        ' + keep);
  }
  fs.writeFileSync(path.join(OUT, 'index.html'), prod);
}
execSync(`node "${path.join(ROOT, 'temp/newpage/build.mjs')}" "${OUT}"`, { stdio: 'inherit' });
must(!rd(path.join(OUT, 'brain/index.html')).includes('noindex'), 'Brain page carries noindex');
// THE PREVIEW HAS ITS build.json TOO (2026-10-27, operator: "wenn die Fehler bekannt und harmlos sind, kann man sie auch
// fixen?"): the pages ask for /build.json (card 07), deploy-dashboard.mjs writes it into its own build, and this preview
// build had none — errors.mjs read a 404 on every run against the preview. Written the same way, never into dashboard/.
if (!APPLY) {
  const m = execSync(`git --git-dir="${path.join(ROOT, 'dashboard', 'source.git')}" log -1 --format="%h %cI"`, { encoding: 'utf8' });
  const [commit, date] = m.trim().split(' ');
  fs.writeFileSync(path.join(OUT, 'build.json'), JSON.stringify({ site_deployed_at: new Date().toISOString(), preview: true, source_mirror: commit ? { commit, date, clone: 'git clone https://brainonbnb.com/source.git' } : null }) + '\n');
}
// THE LINK CARD OF THE FRONT PAGE IS OUR BANNER (operator, 2026-09-28: "the new og card does not always show current and
// correct numbers — take the old banner again, it is our banner everywhere, DexScreener and so on"). The live card
// /m/now.png (27.9.) is gone from the front page; the moment cards of SHARE THIS MOMENT (/m/*) stay as they are.
{
  const b = rd(path.join(OUT, 'brain/index.html'));
  must((b.match(/https:\/\/brainonbnb\.com\/og-banner\.png/g) || []).length >= 2, 'og/twitter banner tags not found on the Brain page');
  must(!/\/m\/now\.png/.test(b), 'the Brain page still names /m/now.png as its link card');
}

// 3) worker routes
{
  let w = rd(path.join(OUT, '_worker.js'));
  const snip = rd(path.join(import.meta.dirname, 'golive-worker-snippet.js'));
  if (!w.includes('THE BRAIN PAGE IS THE FRONT PAGE')) {
    const at = w.lastIndexOf('    const response = await env.ASSETS.fetch(request);'); must(at > 0, 'final asset fetch not found in _worker.js');
    w = w.slice(0, at) + snip.split('// ---- helper ----')[0] + '\n' + w.slice(at) + '\n' + snip.split('// ---- helper ----')[1];
    fs.writeFileSync(path.join(OUT, '_worker.js'), w);
  }
}
// 4) CSP
{
  let h = rd(path.join(OUT, '_headers'));
  h = h.replace("img-src 'self' data: https:", "img-src 'self' data: blob: https:")
    .replace("connect-src 'self' https://bsc-dataseed", "connect-src 'self' https://bobai-tg-bot.bobbuildonbnb.workers.dev https://bsc-dataseed")
    .replace("frame-ancestors 'none'", "frame-ancestors 'self'");
  // the terminal plays each clip from one download kept in memory (a blob: URL): from the network the two players fetched
  // every clip again and again, 4.2 of 4.8 MB in three minutes (2026-10-06). media-src allows our own memory, nothing else
  if (!h.includes('media-src')) h = h.replace("font-src 'self' data:", "media-src 'self' blob:; font-src 'self' data:");
  must(h.includes("frame-ancestors 'self'") && h.includes('blob:') && h.includes('bobai-tg-bot') && h.includes("media-src 'self' blob:"), 'CSP not patched');
  fs.writeFileSync(path.join(OUT, '_headers'), h);
}
// 5) routes
{
  const r = JSON.parse(rd(path.join(OUT, '_routes.json')));
  const add = ['/', '/index.html', '/classic', '/classic/', '/brain', '/brain/', '/brain/index.html'];
  for (const k of ['scanner', 'registry', 'list', 'services', 'defi', 'liquidity', 'agents', 'nft', 'library', 'whitepaper', 'advantage', 'session', 'source', 'token', 'faq', 'roadmap', 'archive', 'board', 'jobs', 'settle', 'venus', 'pass', 'set-and-earn']) add.push('/' + k, '/' + k + '.html');
  add.push('/sitemap.xml', '/screener', '/screener.html', '/agent', '/agent/*', '/agent.html'); // the screener and the agent chart open in a window too (2026-10-12: without these the worker never ran for them, so inside a window they had no window look and their links left the window)
  add.push('/og/*'); // the share card of a scan (2026-10-13), proxied to worker-og in _worker.js
  add.push('/brainscreener', '/brainscreener/*', '/game', '/game/*', '/worldcup', '/worldcup/*', '/builder', '/builder/*'); // builder sheet: password in _worker.js
  r.include = [...new Set([...r.include, ...add])];
  must(r.include.length <= 100, 'Pages allows at most 100 route rules');
  fs.writeFileSync(path.join(OUT, '_routes.json'), JSON.stringify(r, null, 2) + '\n');
}
// the clips stay out of git (and so out of the public mirror): 20 MB of video that changes every day of shooting
if (APPLY) {
  const gi = path.join(OUT, '.gitignore'), line = 'terminal/anim/';
  const cur = fs.existsSync(gi) ? rd(gi) : '';
  if (!cur.split(/\r?\n/).includes(line)) fs.writeFileSync(gi, cur + (cur && !cur.endsWith('\n') ? '\n' : '') + line + '\n');
}
console.log(APPLY ? 'applied to dashboard/ — now: node scripts/deploy-dashboard.mjs' : 'golive build ready:', OUT);
// THE REVIEW PAGE FOLLOWS EVERY GO-LIVE (operator 2026-10-04: "the review page
// must always be current and correct"): clippage.py reads cut.txt and the
// live clip list, so it is rebuilt the moment either can have changed.
if (APPLY) {
  try { execSync('python temp/terminal/clippage.py', { cwd: ROOT, stdio: 'inherit' }); }
  catch { console.log('WARN: review page not rebuilt — run python temp/terminal/clippage.py'); }
}
if (process.argv.includes('--preview')) {
  execSync(`npx wrangler pages deploy "${OUT}" --project-name=bobai-dashboard --branch=golive --commit-dirty=true`, { cwd: ROOT, stdio: 'inherit' });
}
