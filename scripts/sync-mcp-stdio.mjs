// The stdio package (mcp/server.mjs) describes its tools as the hosted server does.
//
// WHY (2026-10-14): the package is what Glama builds from the Dockerfile and what an npx user runs, and its
// descriptions had drifted from https://brainonbnb.com/mcp in 18 of 23 tools — one still told agents a $BOBAI
// trade needs "minimum 15% slippage", which the hosted server stopped saying when the tax was measured. The
// hosted server is the one that is maintained; this copies its descriptions, input schemas and annotations into
// a generated block of the package. How the package answers (its REST mapping and handlers) is not touched.
//
//   node scripts/sync-mcp-stdio.mjs           write the block from the live hosted server
//   node scripts/sync-mcp-stdio.mjs --check   exit 1 when the package differs from the hosted server
//
// Run it after every deploy that changes a tool's wording on the hosted server.
import fs from 'node:fs';
import path from 'node:path';

const FILE = path.resolve(import.meta.dirname, '..', 'mcp', 'server.mjs');
const START = '// GENERATED by scripts/sync-mcp-stdio.mjs from https://brainonbnb.com/mcp — do not edit by hand';
const END = '// END GENERATED';

// exitCode, not process.exit(): on Windows an exit with the fetch's handle still closing aborts with 127 (a false red)
process.exitCode = await (async () => {
  const r = await fetch('https://brainonbnb.com/mcp', { method: 'POST', headers: { 'content-type': 'application/json', accept: 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method: 'tools/list' }) });
  const tools = (await r.json())?.result?.tools;
  if (!Array.isArray(tools) || !tools.length) { console.error('the hosted server returned no tool list'); return 1; }

  const src = fs.readFileSync(FILE, 'utf8');
  const toolsSrc = src.slice(src.indexOf('const TOOLS = ['), src.indexOf('\n];', src.indexOf('const TOOLS = [')));
  const local = [...toolsSrc.matchAll(/^ {2}\{ name: '([a-z0-9_]+)'/gm)].map((m) => m[1]);
  const hosted = {};
  for (const t of tools) if (local.includes(t.name)) hosted[t.name] = { description: t.description, inputSchema: t.inputSchema, ...(t.annotations ? { annotations: t.annotations } : {}) };
  const missing = local.filter((n) => !hosted[n]);
  if (missing.length) console.log(`not on the hosted server, kept as written: ${missing.join(', ')}`);

  const block = `${START}\nconst HOSTED = ${JSON.stringify(hosted)};\n${END}`;
  const at = src.indexOf(START);
  const next = at >= 0
    ? src.slice(0, at) + block + src.slice(src.indexOf(END, at) + END.length)
    : src.replace(/\n\];\n/, `\n];\n\n${block}\nfor (const t of TOOLS) if (HOSTED[t.name]) Object.assign(t, HOSTED[t.name]);\n`);
  if (next === src) { console.log(`in step: ${Object.keys(hosted).length} tools as the hosted server describes them`); return 0; }
  if (process.argv.includes('--check')) { console.error('mcp/server.mjs differs from the hosted server — run node scripts/sync-mcp-stdio.mjs'); return 1; }
  fs.writeFileSync(FILE, next);
  console.log(`wrote ${Object.keys(hosted).length} tool definitions from the hosted server into mcp/server.mjs`);
  return 0;
})();
